let currentLang = localStorage.getItem('ospat_lang') || 'ru';

function t(key, fallback = '') {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['ru'];
    return dict[key] !== undefined ? dict[key] : (fallback || key);
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'ru';
    currentLang = lang;
    localStorage.setItem('ospat_lang', lang);

    // Update active state in switcher UI
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (translated) {
            el.innerHTML = translated;
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translated = t(key);
        if (translated) {
            el.setAttribute('placeholder', translated);
        }
    });

    // Re-render components that have dynamic language content
    if (typeof window.initWcsTool === 'function') {
        window.initWcsTool();
    }
    if (typeof window.updateSessionUI === 'function') {
        window.updateSessionUI();
    }
    if (typeof window.loadMaterials === 'function') {
        window.loadMaterials();
    }
    if (typeof window.checkTelegramConnection === 'function') {
        window.checkTelegramConnection();
    }
    if (typeof window.updateThemeToggleUI === 'function') {
        window.updateThemeToggleUI();
    }
    if (window.lucide) {
        window.lucide.createIcons();
    }
}

window.TRANSLATIONS = TRANSLATIONS;
window.currentLang = currentLang;
window.t = t;
window.setLanguage = setLanguage;
